"""Capability `finance`: the books. Read the figures, explain them, file the report. Never move money.

Every number comes from core/finance.py, computed from the payment record and the vault. The agent's
own words go only into the commentary of a report; it cannot type a figure into a receipt or a table.
"""
from __future__ import annotations

import json

from core import finance, store
from core.provenance import Origin, Result
from core.registry import register


@register("finance_report", "finance",
          "The month's books, computed from the payment record: revenue, refunds, revenue shares, vendor spend, "
          "AI cost, net and margin, by offering and by vendor. `month` is YYYY-MM; empty means this month.",
          {"month": {"type": "string"}}, ["month"])
def finance_report(month: str = "") -> Result:
    try:
        r = finance.report(month or None)
    except ValueError:
        return Result(None, Origin.MISSING, "books", note="month must look like 2026-11")
    r["entries"] = r["entries"][:40]
    return Result(r, Origin.CACHED, "AERA books", note="figures computed in code; quote them, do not recompute")


@register("reconcile_books", "finance",
          "Compare AERA's record with the vault on chain: the balance it should hold, orders paid on chain but not "
          "recorded, payments still in flight. Every difference is named.", {}, [])
def reconcile_books() -> Result:
    r = finance.reconcile()
    origin = Origin.LIVE if r.get("balance_usd") is not None else Origin.DERIVED
    return Result(r, origin, "vault + AERA books")


@register("save_monthly_report", "finance",
          "File the month's report as a PDF document: the figures and the reconciliation are filled in by the books; "
          "`commentary` is your explanation (what drove the month, what looks wrong, what a person should check).",
          {"month": {"type": "string"}, "commentary": {"type": "string"}}, ["month", "commentary"], writes=True)
def save_monthly_report(month: str, commentary: str) -> Result:
    try:
        r = finance.report(month or None)
    except ValueError:
        return Result(None, Origin.MISSING, "books", note="month must look like 2026-11")
    from core import registry
    md = finance.report_markdown(r, commentary[:6000], finance.reconcile())
    meta = {"title": f"Monthly report — {r['label']}", "format": "pdf", "order_id": None,
            "run_id": registry.current_run(), "kind": "finance_report", "month": r["month"]}
    f = store.save_file(f"doc:{meta['title']}", "text/markdown;" + json.dumps(meta), md,
                        by=f"agent:{registry.current_agent() or 'finance'}")
    return Result({**f, "title": meta["title"], "month": r["month"], "net_usd": r["net_usd"]}, Origin.DERIVED, "documents")


@register("receipt_for_order", "finance",
          "The receipt for a paid order: number, amount, payer, rail, transaction. The PDF is generated by the books "
          "and is the same every time; the customer can download it from the order's status page.",
          {"order_id": {"type": "string"}}, ["order_id"])
def receipt_for_order(order_id: str) -> Result:
    r = finance.receipt_data(order_id)
    if not r:
        return Result(None, Origin.MISSING, "orders", note=f"no receipt: order {order_id} is unknown or not paid")
    return Result({**r, "pdf": f"/public/orders/{order_id}/receipt.pdf"}, Origin.CACHED, "AERA books")


def demo() -> None:
    from core import business, registry
    store.save_profile(business.EXAMPLE, by="check")
    store.create_order("ord_fin1", "brief", 15, {}, customer="ana.testnet", status="paid")
    store.record_payment("in", "simulated", "ana.testnet", 15, "usdc", "sent", detail={"order_id": "ord_fin1"})
    assert finance_report("").value["revenue_usd"] == 15
    assert finance_report("nonsense").origin is Origin.MISSING
    assert receipt_for_order("ord_fin1").value["number"] == "R-FIN1"
    rid = store.start_run(store.record_work_item("request", "close the books", "api", {}))
    with registry.bind_run(rid):
        saved = save_monthly_report("", "One order, no vendor spend.")
    assert saved.value["net_usd"] == 15 and "Monthly report" in saved.value["title"]
    text = store.get_file(saved.value["id"])["text"]
    assert "| Revenue | $15.00 |" in text and "One order, no vendor spend." in text
    print("tools/finance ok: figures from the books ✓ · report filed with the agent's notes only ✓ · receipts ✓")


if __name__ == "__main__":
    from core.config import fixtures_only
    fixtures_only(__file__, "AERA_TOOLS_FINANCE_CHECK")
    demo()
